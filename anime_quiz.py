def giga_request(prompt, token, max_tokens=300):
    headers = {
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json",
        "X-Request-ID": str(uuid.uuid4()),
        "X-Session-ID": str(uuid.uuid4()),
        "User-Agent": "AnimeQuizBot/1.0"
    }
    payload = {
        "model": "GigaChat-3-Ultra",
        "messages": [
            {"role": "system", "content": "Ты — ведущий викторины по аниме."},
            {"role": "user", "content": prompt}
        ],
        "temperature": 0.8,
        "max_tokens": max_tokens
    }
    try:
        response = requests.post(
            "https://api.giga.chat/v1/chat/completions",
            headers=headers,
            json=payload,
            timeout=30,
            verify=False
        )
        response.raise_for_status()
        data = response.json()
        return data["choices"][0]["message"]["content"].strip()
    except Exception as e:
        print(f"Ошибка GigaChat: {e}")
        return ""

def clean_question(text):
    """Убирает дисклеймеры и мусор из ответа GigaChat."""
    if not text:
        return ""
    # Удаляем стандартные дисклеймеры
    text = re.sub(r'Как и любая языковая модель.*?информация\.', '', text, flags=re.IGNORECASE | re.DOTALL)
    text = re.sub(r'Ответ сгенерирован нейросетевой моделью.*?информация\.', '', text, flags=re.IGNORECASE | re.DOTALL)
    # Убираем возможные приписки после вопроса
    lines = [line.strip() for line in text.split('\n') if line.strip()]
    if lines:
        # Берём первую строку (обычно сам вопрос)
        question = lines[0]
        # Если строка слишком короткая, берём всё
        if len(question) < 10 and len(lines) > 1:
            question = ' '.join(lines[:2])
        question = re.sub(r'\.{3,}$', '', question).strip()
        return question
    return ""

